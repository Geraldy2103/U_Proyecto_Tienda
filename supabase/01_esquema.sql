create policy "solo admin"      on sedes      for all using (es_admin()) with check (es_admin());
create policy "lectura publica" on directores for select using (true);
create policy "solo admin"      on directores for all using (es_admin()) with check (es_admin());
create policy "lectura publica" on asesores   for select using (true);
create policy "solo admin"      on asesores   for all using (es_admin()) with check (es_admin());

-- Zonas de envío: cualquiera las lee (para calcular el envío en la página); solo el admin las cambia
create policy "lectura publica" on zonas_envio for select using (true);
create policy "solo admin"      on zonas_envio for all using (es_admin()) with check (es_admin());

-- Proveedores: solo admin (incluso para leer)
create policy "solo admin" on proveedores for all using (es_admin()) with check (es_admin());

-- Perfiles: cada usuario ve el suyo; el admin ve todos. Nadie se cambia el rol desde la página.
create policy "ver mi perfil" on perfiles for select using (id = auth.uid() or es_admin());

-- Pedidos: cada cliente ve los suyos y el admin todos. Se crean solo con confirmar_pedido().
create policy "ver mis pedidos" on pedidos for select to authenticated
    using (idusuario = auth.uid() or es_admin());
create policy "admin actualiza" on pedidos for update to authenticated
    using (es_admin()) with check (es_admin());
create policy "ver detalle de mis pedidos" on pedido_detalle for select to authenticated
    using (exists (select 1 from pedidos p where p.idpedido = pedido_detalle.idpedido
                   and (p.idusuario = auth.uid() or es_admin())));

-- Solicitudes: el cliente crea las suyas; ve las suyas; el admin ve y atiende todas
create policy "crear mi solicitud" on solicitudes_mayoristas for insert to authenticated
    with check (idusuario = auth.uid());
create policy "ver mis solicitudes" on solicitudes_mayoristas for select to authenticated
    using (idusuario = auth.uid() or es_admin());
create policy "admin actualiza" on solicitudes_mayoristas for update to authenticated
    using (es_admin()) with check (es_admin());


