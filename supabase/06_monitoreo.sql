-- 1. Registro de eventos ------------------------------------------------
create table if not exists registro_eventos (
    id         bigint generated by default as identity primary key,
    fecha      timestamptz not null default now(),
    tipo       text not null check (tipo in ('error', 'error_api', 'aviso')),
    mensaje    text not null check (length(mensaje) between 1 and 500),
    detalle    text check (length(detalle) <= 500),
    pagina     text check (length(pagina) <= 80),
    navegador  text check (length(navegador) <= 200),
    idusuario  uuid default auth.uid() references auth.users (id) on delete set null
);

create index if not exists registro_eventos_fecha on registro_eventos (fecha desc);

alter table registro_eventos enable row level security;

-- Cualquiera (incluso un visitante sin cuenta) puede REGISTRAR un error, pero solo a su nombre
drop policy if exists "registrar evento" on registro_eventos;
create policy "registrar evento" on registro_eventos for insert to anon, authenticated
    with check (idusuario is null or idusuario = auth.uid());

-- Solo el administrador lee y limpia el registro
drop policy if exists "admin lee eventos" on registro_eventos;
create policy "admin lee eventos" on registro_eventos for select to authenticated using (es_admin());
drop policy if exists "admin borra eventos" on registro_eventos;
create policy "admin borra eventos" on registro_eventos for delete to authenticated using (es_admin());

grant insert on registro_eventos to anon, authenticated;
grant select, delete on registro_eventos to authenticated;

-- 2. Estado del sistema (solo admin) -------------------------------------
create or replace function estado_sistema() returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
    if not es_admin() then
        raise exception 'Solo el administrador puede ver el estado del sistema';
    end if;
    return jsonb_build_object(
        'hora_servidor',      now(),
        'tamano_base',        pg_size_pretty(pg_database_size(current_database())),
        'productos',          (select count(*) from productos),
        'clientes',           (select count(*) from perfiles where rol = 'cliente'),
        'asesores_con_cuenta',(select count(*) from perfiles where rol = 'asesor'),
        'administradores',    (select count(*) from perfiles where rol = 'admin'),
        'pedidos_hoy',        (select count(*) from pedidos where fecha >= date_trunc('day', now())),
        'pedidos_total',      (select count(*) from pedidos),
        'errores_24h',        (select count(*) from registro_eventos
                               where tipo <> 'aviso' and fecha >= now() - interval '24 hours')
    );
end;
$$;

revoke execute on function estado_sistema() from public, anon;
grant  execute on function estado_sistema() to authenticated;

